/** Confere a restrição de alinhamento da classe. */
export function alinhamentoValido(classeId, alinh) {
  if (!alinh) return true;
  const leal = alinh.startsWith('Leal'), neutroEixo = alinh === 'Neutro' || alinh.includes('Neutro');
  switch (classeId) {
    case 'barbaro': case 'bardo': return !leal;
    case 'monge': return leal;
    case 'paladino': return alinh === 'Leal e Bom';
    case 'druida': return neutroEixo;
    default: return true;
  }
}
